import { Buffer } from "node:buffer";
import { createHash } from "node:crypto";

export function sha256(bytes: Uint8Array | string): string {
  return createHash("sha256").update(bytes).digest("hex");
}

export function crc32(bytes: Uint8Array): number {
  let value = 0xffffffff;
  for (const byte of bytes) {
    value ^= byte;
    for (let bit = 0; bit < 8; bit++) {
      value = (value >>> 1) ^ (value & 1 ? 0xedb88320 : 0);
    }
  }
  return (value ^ 0xffffffff) >>> 0;
}

export function gzipStored(bytes: Uint8Array): Uint8Array {
  const blocks = Math.max(1, Math.ceil(bytes.length / 65535));
  const output = new Uint8Array(10 + blocks * 5 + bytes.length + 8);
  output.set([0x1f, 0x8b, 8, 0, 0, 0, 0, 0, 0, 0xff]);
  const view = new DataView(output.buffer);
  let at = 10;
  for (let index = 0; index < blocks; index++) {
    const start = index * 65535;
    const size = Math.min(65535, bytes.length - start);
    output[at] = index === blocks - 1 ? 1 : 0;
    view.setUint16(at + 1, size, true);
    view.setUint16(at + 3, size ^ 0xffff, true);
    output.set(bytes.subarray(start, start + size), at + 5);
    at += 5 + size;
  }
  view.setUint32(at, crc32(bytes), true);
  view.setUint32(at + 4, bytes.length >>> 0, true);
  return output;
}

export function claudeSnapshotModule(bytes: Uint8Array): string {
  const base64 = Buffer.from(bytes).toString("base64");
  const chunks: string[] = [];
  for (let at = 0; at < base64.length; at += 96) {
    chunks.push(`    ${JSON.stringify(base64.slice(at, at + 96))},`);
  }
  return [
    "/** Generated by deno task deps from the verified Claude recipe. */",
    'import type { EmbeddedAdapterSnapshot } from "../src/adapter-snapshot-type.ts";',
    "",
    "export const CLAUDE_SNAPSHOT: EmbeddedAdapterSnapshot = Object.freeze({",
    '  provider: "claude",',
    '  package: "@agentclientprotocol/claude-agent-acp",',
    '  version: "0.70.0",',
    `  sha256: ${JSON.stringify(sha256(bytes))},`,
    `  byteLength: ${bytes.length},`,
    "  base64: [",
    ...chunks,
    '  ].join(""),',
    "});",
    "",
  ].join("\n");
}
