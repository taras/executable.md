import { Err, Ok, scoped } from "effection";
import type { Operation, Result } from "effection";
import type { Json, SyntaxSymbols } from "@executablemd/core";
import { gitPlugin } from "@executablemd/git";
import { installPlugins } from "../../packages/cli/src/plugin-host.ts";
import { syntaxSymbols } from "../../packages/cli/src/syntax.ts";

type Entry = SyntaxSymbols["categories"][number]["entries"][number];

export function* constructInventory(): Operation<Result<string>> {
  try {
    const symbols = yield* scoped(function* () {
      const plugins = yield* installPlugins([gitPlugin], {
        command: "syntax",
        args: ["syntax"],
      });
      return yield* syntaxSymbols([], plugins);
    });
    return Ok(renderConstructInventory(symbols));
  } catch (error) {
    return Err(error instanceof Error ? error : new Error(String(error)));
  }
}

function renderConstructInventory(symbols: SyntaxSymbols): string {
  const lines = [
    "# Construct inventory",
    "",
    "<!-- Generated by deno task docs:inventory. Do not edit by hand. -->",
    "",
    `Source: Syntax symbols version ${symbols.version}, through the same boundary as ` +
      "`<Syntax />` and `xmd syntax`. This profile explicitly selects " +
      "`@executablemd/git`, with no repository includes.",
    "",
    "A non-normative table of the selected public vocabulary. In props, `?` marks " +
      "an optional prop and `capture` marks a component-evaluated prop with no " +
      "declared schema.",
    "",
    "| Construct | Kind | Origin package | Declared props summary | Returns summary |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const category of symbols.categories) {
    for (const entry of category.entries) {
      lines.push(
        `| ${[entry.name, kind(entry), origin(entry), props(entry), returns(entry)].map(cell).join(" | ")} |`,
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

function kind(entry: Entry): string {
  if (entry.kind === "structural") {
    return "structural";
  }
  if (entry.sourceKind === "protected") {
    return "protected";
  }
  if (entry.sourceKind === "declared-markdown") {
    return "declared Markdown";
  }
  if (entry.sourceKind === "registered") {
    return entry.origin.kind === "registered" && entry.origin.reserved
      ? "reserved component"
      : "default component";
  }
  throw new Error(
    `inventory profile contains an unexpected ${entry.sourceKind} component: ${entry.name}`,
  );
}

function origin(entry: Entry): string {
  if (!("origin" in entry.origin)) {
    return "not declared";
  }
  return /^(@[^/]+\/[^/]+)(?:\/|$)/.exec(entry.origin.origin)?.[1] ?? entry.origin.origin;
}

function props(entry: Entry): string {
  if (!("props" in entry)) {
    return "not declared in symbols";
  }
  const properties = entry.props.properties;
  const names: string[] = [];
  if (typeof properties === "object" && properties !== null && !Array.isArray(properties)) {
    const required = Array.isArray(entry.props.required) ? entry.props.required : [];
    for (const [name, schema] of Object.entries(properties)) {
      names.push(`${name}${required.includes(name) ? "" : "?"}: ${schemaType(schema)}`);
    }
  }
  if ("captures" in entry) {
    names.push(...entry.captures.map((name) => `${name}: capture`));
  }
  return names.length === 0 ? "no individual props declared" : names.join("; ");
}

function returns(entry: Entry): string {
  if (!("returns" in entry)) {
    return "not declared in symbols";
  }
  return `${entry.returnMode}: ${schemaType(entry.returns)}`;
}

function schemaType(schema: Json): string {
  if (typeof schema !== "object" || schema === null || Array.isArray(schema)) {
    return "schema";
  }
  if (typeof schema.type === "string") {
    return schema.type;
  }
  if (Array.isArray(schema.type) && schema.type.every((value) => typeof value === "string")) {
    return schema.type.join(" | ");
  }
  return "schema";
}

function cell(text: string): string {
  return `<code>${text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll("|", "&#124;")
    .replaceAll("\r", "&#13;")
    .replaceAll("\n", "&#10;")}</code>`;
}
